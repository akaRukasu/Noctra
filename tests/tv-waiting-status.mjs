import assert from 'node:assert/strict';
import {playerFixture} from './v200048-tv-recovery.mjs';
const p = await playerFixture('Movix', false, {section:'channels'});
const statuses=[];
p.deps.setTvPlaybackStatus=(text,state)=>statuses.push({text,state});
p.video.paused=false;
p.video.readyState=4;
p.video.currentTime=10;
p.video.dispatchEvent(new Event('playing'));
p.video.dispatchEvent(new Event('waiting'));
assert.equal(statuses.at(-1).state,'loading');
p.video.dispatchEvent(new Event('timeupdate'));
assert.equal(statuses.at(-1).state,'loading','Frozen picture must keep warning');
p.video.currentTime=11;
p.video.paused=true;
p.video.dispatchEvent(new Event('timeupdate'));
assert.equal(statuses.at(-1).state,'loading','Manual pause is not a recovery');
p.video.paused=false;
p.video.seeking=true;
p.video.dispatchEvent(new Event('timeupdate'));
assert.equal(statuses.at(-1).state,'loading','Seeking is not a recovery');
p.video.seeking=false;
p.video.dispatchEvent(new Event('timeupdate'));
assert.equal(statuses.at(-1).state,'playing','Actual progression clears stale waiting without playing event');
console.log('TV waiting status: freeze, pause, seek and actual recovery passed');
