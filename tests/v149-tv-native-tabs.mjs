assert.ok(server.includes('tvCatalogFromJackTvWithFallback') && server.includes('tvCatalogFromDailyWithFallback'));
assert.ok(server.includes("['live-tv', 'Live TV']") && server.includes("/live-tv\\/"));
assert.ok(server.includes("id: 'streamsports99-sports'"));
assert.ok(css.includes('Noctra V149 — fournisseurs TV visibles sans défilement horizontal'));
assert.ok(css.includes('grid-template-columns: repeat(3, minmax(0,1fr))'));
